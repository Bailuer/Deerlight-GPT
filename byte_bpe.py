    tokenizer = ByteBPETokenizer(vocab_size=265)
    tokenizer.train("banana banana banana")
    print("Merge Rules:", tokenizer.merges)
    for text in ["banana", "Deerlight GPT", "鹿光 🦌", "<BOS>"]:
        ids = tokenizer.encode(text)
        # ASCII escapes keep this demo printable even in legacy Windows terminals.
        print(f"Text: {ascii(text)} | IDs: {ids} | Decoded: {ascii(tokenizer.decode(ids))}")
